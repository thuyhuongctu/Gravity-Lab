"""Build src/data/land.ts: simplified country outlines for the globe view.

Input: a Natural Earth admin-0 countries pack (public domain, ne_10m_admin_0_countries),
stored as {"features": [{"iso": ..., "polygons": [[[x0, y0, dx1, dy1, ...], ...], ...]}]}
(polygons -> rings, first ring is the outer one) with
coordinates scaled by 10^decimals and delta-encoded after the first vertex.

Output: {"source": ..., "rings": [[lon0, lat0, dlon1, dlat1, ...], ...]} in tenths of a degree,
delta-encoded, simplified with Douglas-Peucker. Made with Natural Earth.

Usage: python3 scripts/build-land.py <countries.json> src/data/land.ts
"""

import json
import math
import sys

TOLERANCE_DEG = 0.18
MIN_SPAN_DEG = 0.9


def decode(ring, scale):
    pts, x, y = [], 0, 0
    for i in range(0, len(ring) - 1, 2):
        if i == 0:
            x, y = ring[0], ring[1]
        else:
            x += ring[i]
            y += ring[i + 1]
        pts.append((x / scale, y / scale))
    return pts


def perp(p, a, b):
    ax, ay = a
    bx, by = b
    px, py = p
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        best, idx = 0.0, -1
        for k in range(i + 1, j):
            d = perp(pts[k], pts[i], pts[j])
            if d > best:
                best, idx = d, k
        if best > tol and idx > 0:
            keep[idx] = True
            stack.append((i, idx))
            stack.append((idx, j))
    return [p for p, k in zip(pts, keep) if k]


def main(src, dst):
    data = json.load(open(src, encoding="utf-8"))
    scale = 10 ** int(data["meta"]["decimals"])
    rings = []
    for feature in data["features"]:
        for polygon in feature.get("polygons", []):
            if not polygon or not polygon[0]:
                continue
            pts = decode(polygon[0], scale)
            lons = [p[0] for p in pts]
            lats = [p[1] for p in pts]
            if max(max(lons) - min(lons), max(lats) - min(lats)) < MIN_SPAN_DEG:
                continue
            pts = simplify(pts + [pts[0]], TOLERANCE_DEG)[:-1]
            if len(pts) < 4:
                continue
            enc, px, py = [], 0, 0
            for k, (lon, lat) in enumerate(pts):
                x, y = round(lon * 10), round(lat * 10)
                if k == 0:
                    enc += [x, y]
                elif x != px or y != py:
                    enc += [x - px, y - py]
                px, py = x, y
            if len(enc) >= 8:
                rings.append(enc)
    body = json.dumps(rings, separators=(",", ":"))
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/build-land.py. Made with Natural Earth (public domain).\n")
        f.write("// Outer rings of ne_10m_admin_0_countries, simplified; tenths of a degree,\n")
        f.write("// [lon0, lat0, dlon1, dlat1, ...] delta-encoded.\n")
        f.write("export const LAND_SCALE = 10;\n")
        f.write("export const LAND_RINGS: number[][] = " + body + ";\n")
    print(len(rings), "rings")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
